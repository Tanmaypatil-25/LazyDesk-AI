import { describe, it } from 'node:test';
import assert from 'node:assert';
import {
  validateAndSanitizeAnalysis,
  checkOllamaStatus
} from '../services/ollama.service.js';
import { ALLOWED_CATEGORIES, DEFAULT_CATEGORY } from '../config/constants.js';

describe('Ollama Output Validation and Security', () => {
  it('enforces category allowlist and falls back to default on invalid category', () => {
    const rawParsed = {
      summary: 'Monthly AWS cloud server hosting invoice for October 2026.',
      category: 'HACKED_CATEGORY_TRYING_TO_BYPASS',
      tags: ['cloud', 'aws', 'infrastructure'],
      suggestedFilename: '2026-10-aws-invoice.pdf'
    };

    const validated = validateAndSanitizeAnalysis(rawParsed, 'invoice.pdf');
    assert.strictEqual(validated.category, DEFAULT_CATEGORY);
    assert.strictEqual(validated.summary, rawParsed.summary);
    assert.deepStrictEqual(validated.tags, ['cloud', 'aws', 'infrastructure']);
    assert.strictEqual(validated.suggestedFilename, '2026-10-aws-invoice.pdf');
  });

  it('matches category case-insensitively to the official allowlist', () => {
    const rawParsed = {
      summary: 'Consulting agreement between Alice and Bob.',
      category: 'contracts & legal',
      tags: ['legal', 'agreement'],
      suggestedFilename: '2026-consulting-contract.pdf'
    };

    const validated = validateAndSanitizeAnalysis(rawParsed, 'contract.pdf');
    assert.strictEqual(validated.category, 'Contracts & Legal');
    assert.ok(ALLOWED_CATEGORIES.includes(validated.category));
  });

  it('handles null or empty model outputs safely without crashing', () => {
    const validated = validateAndSanitizeAnalysis(null, 'test.txt');

    assert.ok(typeof validated.summary === 'string');
    assert.strictEqual(validated.category, DEFAULT_CATEGORY);
    assert.ok(Array.isArray(validated.tags));
    assert.ok(validated.suggestedFilename.endsWith('.txt'));
  });

  it('sanitizes malicious suggested filenames generated by the model', () => {
    const rawParsed = {
      summary: 'Resume for senior software engineer.',
      category: 'Identity & Personal',
      tags: ['resume', 'developer'],
      suggestedFilename: '../../../../etc/shadow'
    };

    const validated = validateAndSanitizeAnalysis(rawParsed, 'resume.pdf');
    assert.ok(!validated.suggestedFilename.includes('/'));
    assert.ok(!validated.suggestedFilename.includes('..'));
    assert.ok(validated.suggestedFilename.endsWith('.pdf'));
  });

  it('gracefully reports status when Ollama is unreachable on unused port', async () => {
    const status = await checkOllamaStatus('http://127.0.0.1:54321');
    assert.strictEqual(status.connected, false);
    assert.ok(status.error);
  });
});
